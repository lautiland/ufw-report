use std::fmt::Write as _;
use std::io::Write;
use std::path::Path;

use crate::models::ThreatReport;

/// Output format used by `--findings`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FindingsFormat {
    Json,
    Markdown,
}

impl FindingsFormat {
    /// Resolves the format from the destination path.
    ///
    /// A `.md` extension selects Markdown; every other path (including `-`)
    /// produces JSON.
    #[must_use]
    pub fn resolve(path: &str) -> Self {
        if Path::new(path)
            .extension()
            .is_some_and(|extension| extension.eq_ignore_ascii_case("md"))
        {
            Self::Markdown
        } else {
            Self::Json
        }
    }
}

/// Writes the threat report to `path` in the requested format.
///
/// Use `-` to write to stdout.
///
/// # Errors
///
/// Returns an error if file creation or writing fails.
pub fn write_findings(
    report: &ThreatReport,
    path: &str,
    format: FindingsFormat,
) -> anyhow::Result<()> {
    if path == "-" {
        match format {
            FindingsFormat::Json => {
                serde_json::to_writer_pretty(std::io::stdout().lock(), report)?;
                println!();
            }
            FindingsFormat::Markdown => {
                print!("{}", render_markdown(report));
            }
        }
        return Ok(());
    }

    super::safe::write_output_file(path, |file| match format {
        FindingsFormat::Json => serde_json::to_writer_pretty(file, report).map_err(Into::into),
        FindingsFormat::Markdown => file
            .write_all(render_markdown(report).as_bytes())
            .map_err(Into::into),
    })?;

    tracing::info!("Findings written to {}", path);
    Ok(())
}

/// Renders the report as a Markdown document.
#[must_use]
pub fn render_markdown(report: &ThreatReport) -> String {
    let mut out = String::new();

    writeln!(out, "# UFW Threat Findings").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "Range: {} → {}", report.from, report.to).unwrap();
    writeln!(out).unwrap();

    write_custody(&mut out, report);
    write_summary(&mut out, report);
    write_coverage(&mut out, report);
    write_findings_section(&mut out, report);
    write_profiles(&mut out, report);
    write_subnets(&mut out, report);
    write_disclaimer(&mut out, report);

    writeln!(out, "_Generated by ufw-report (offline, read-only).").unwrap();
    out
}

fn write_custody(out: &mut String, report: &ThreatReport) {
    let custody = &report.custody;

    writeln!(out, "## Chain of custody").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "| Field | Value |").unwrap();
    writeln!(out, "| --- | --- |").unwrap();
    writeln!(
        out,
        "| Executed (UTC) | {} |",
        custody.generated_at.format("%Y-%m-%dT%H:%M:%SZ")
    )
    .unwrap();
    writeln!(
        out,
        "| Hostname | {} |",
        custody.hostname.as_deref().unwrap_or("-")
    )
    .unwrap();
    writeln!(out, "| Tool version | {} |", custody.tool_version).unwrap();
    writeln!(
        out,
        "| Configuration SHA-256 | `{}` |",
        if custody.config_sha256.is_empty() {
            "-"
        } else {
            &custody.config_sha256
        }
    )
    .unwrap();
    writeln!(out).unwrap();

    if !custody.effective_config.is_empty() {
        writeln!(out, "### Effective configuration").unwrap();
        writeln!(out).unwrap();
        writeln!(out, "```toml").unwrap();
        write!(out, "{}", custody.effective_config).unwrap();
        if !custody.effective_config.ends_with('\n') {
            writeln!(out).unwrap();
        }
        writeln!(out, "```").unwrap();
        writeln!(out).unwrap();
    }

    writeln!(out, "### Input files").unwrap();
    writeln!(out).unwrap();
    if custody.files.is_empty() {
        writeln!(out, "No input files were recorded for this run.").unwrap();
    } else {
        writeln!(
            out,
            "| Path | Size (bytes) | SHA-256 | Parsed blocks | Status |"
        )
        .unwrap();
        writeln!(out, "| --- | ---: | --- | ---: | --- |").unwrap();
        for file in &custody.files {
            let digest = if file.sha256.is_empty() {
                "-".to_string()
            } else {
                format!("`{}`", file.sha256)
            };
            writeln!(
                out,
                "| `{}` | {} | {} | {}/{} | {} |",
                file.path,
                file.size_bytes,
                digest,
                file.parse_stats.parsed_block_lines(),
                file.parse_stats.block_lines,
                file_status(file),
            )
            .unwrap();
        }
    }
    writeln!(out).unwrap();
}

fn file_status(file: &crate::models::EvidenceFile) -> String {
    if let Some(error) = &file.error {
        return format!("failed ({})", error.message);
    }
    if file.from_cache {
        "ok (from cache)".to_string()
    } else {
        "ok".to_string()
    }
}

fn write_disclaimer(out: &mut String, report: &ThreatReport) {
    writeln!(out, "## Disclaimer").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "{}", report.custody.disclaimer).unwrap();
    writeln!(out).unwrap();
}

fn write_summary(out: &mut String, report: &ThreatReport) {
    let summary = &report.summary;

    writeln!(out, "## Summary").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "| Metric | Value |").unwrap();
    writeln!(out, "| --- | ---: |").unwrap();
    writeln!(out, "| Sources seen | {} |", summary.total_sources).unwrap();
    writeln!(out, "| Ranked sources | {} |", summary.ranked_sources).unwrap();
    writeln!(out, "| Critical | {} |", summary.critical).unwrap();
    writeln!(out, "| High | {} |", summary.high).unwrap();
    writeln!(out, "| Medium | {} |", summary.medium).unwrap();
    writeln!(out, "| Low | {} |", summary.low).unwrap();
    writeln!(out, "| Findings | {} |", summary.total_findings).unwrap();
    match &summary.top_source {
        Some(source) => {
            writeln!(
                out,
                "| Top source | `{source}` (score {}) |",
                summary.top_score
            )
            .unwrap();
        }
        None => {
            writeln!(out, "| Top source | - |").unwrap();
        }
    }
    writeln!(out).unwrap();
}

fn write_coverage(out: &mut String, report: &ThreatReport) {
    let coverage = &report.coverage;
    let stats = &coverage.stats;

    writeln!(out, "## Log coverage").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "| Metric | Value |").unwrap();
    writeln!(out, "| --- | ---: |").unwrap();
    writeln!(out, "| Coverage | {:.2}% |", coverage.coverage_pct).unwrap();
    writeln!(out, "| Hours in range | {} |", coverage.hours_in_range).unwrap();
    writeln!(out, "| Hours with data | {} |", coverage.hours_with_data).unwrap();
    writeln!(out, "| Missing hours | {} |", coverage.missing_hours).unwrap();
    writeln!(
        out,
        "| Longest gap | {} hours |",
        coverage.longest_gap_hours
    )
    .unwrap();
    writeln!(out, "| Lines read | {} |", stats.total_lines).unwrap();
    writeln!(out, "| Block lines | {} |", stats.block_lines).unwrap();
    writeln!(out, "| Allow lines | {} |", stats.allow_lines).unwrap();
    writeln!(out, "| Audit lines | {} |", stats.audit_lines).unwrap();
    writeln!(out, "| Other lines | {} |", stats.other_lines).unwrap();
    writeln!(
        out,
        "| Unparsed block lines | {} |",
        stats.unparsed_block_lines
    )
    .unwrap();
    writeln!(out, "| Out-of-order lines | {} |", stats.out_of_order_lines).unwrap();
    writeln!(out, "| Future-dated entries | {} |", stats.future_entries).unwrap();
    writeln!(out).unwrap();
}

fn write_findings_section(out: &mut String, report: &ThreatReport) {
    writeln!(out, "## Findings").unwrap();
    writeln!(out).unwrap();
    if report.findings.is_empty() {
        writeln!(
            out,
            "No threat findings were detected in the selected range."
        )
        .unwrap();
    } else {
        writeln!(
            out,
            "| Severity | Kind | ATT&CK | Source | Target | Ports | Protocols | First | Last | Occurrences | Peak | Evidence |"
        )
        .unwrap();
        writeln!(
            out,
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- | ---: | ---: | --- |"
        )
        .unwrap();
        for finding in &report.findings {
            writeln!(
                out,
                "| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |",
                finding.severity.label(),
                finding.kind.label(),
                finding.technique.as_deref().unwrap_or("-"),
                format_sources(finding),
                finding.target_ip.as_deref().unwrap_or("-"),
                format_ports(finding),
                format_protocols(finding),
                finding.first_timestamp.format("%Y-%m-%d %H:%M:%S"),
                finding.last_timestamp.format("%Y-%m-%d %H:%M:%S"),
                finding.occurrences,
                finding.peak,
                finding.evidence,
            )
            .unwrap();
        }
    }
    writeln!(out).unwrap();
}

fn format_sources(finding: &crate::models::ThreatFinding) -> String {
    if let Some(source) = &finding.source_ip {
        return format!("`{source}`");
    }
    if finding.sources.is_empty() {
        return "-".to_string();
    }
    let mut sources: Vec<String> = finding
        .sources
        .iter()
        .take(5)
        .map(|source| format!("`{source}`"))
        .collect();
    if finding.sources.len() > 5 {
        sources.push(format!("+{} more", finding.sources.len() - 5));
    }
    sources.join(", ")
}

fn format_ports(finding: &crate::models::ThreatFinding) -> String {
    if !finding.ports.is_empty() {
        let mut ports: Vec<String> = finding
            .ports
            .iter()
            .take(10)
            .map(ToString::to_string)
            .collect();
        if finding.ports.len() > 10 {
            ports.push(format!("+{} more", finding.ports.len() - 10));
        }
        return ports.join(", ");
    }
    finding
        .target_port
        .map_or_else(|| "-".to_string(), |port| port.to_string())
}

fn format_protocols(finding: &crate::models::ThreatFinding) -> String {
    if finding.protocols.is_empty() {
        "-".to_string()
    } else {
        finding.protocols.join(", ")
    }
}

fn write_profiles(out: &mut String, report: &ThreatReport) {
    writeln!(out, "## Threat sources").unwrap();
    writeln!(out).unwrap();
    if report.profiles.is_empty() {
        writeln!(out, "No source reached the configured minimum risk score.").unwrap();
    } else {
        writeln!(
            out,
            "| # | IP | Score | Severity | Tags | Blocks | Ports | Days | First | Last |"
        )
        .unwrap();
        writeln!(
            out,
            "| ---: | --- | ---: | --- | --- | ---: | ---: | ---: | --- | --- |"
        )
        .unwrap();
        for (index, profile) in report.profiles.iter().enumerate() {
            let tags = profile
                .findings
                .iter()
                .map(|kind| kind.short_label())
                .collect::<Vec<_>>()
                .join(", ");
            writeln!(
                out,
                "| {} | `{}` | {} | {} | {} | {} | {} | {} | {} | {} |",
                index + 1,
                profile.ip,
                profile.risk_score,
                profile.severity.label(),
                if tags.is_empty() { "-" } else { &tags },
                profile.total_blocks,
                profile.distinct_dst_ports,
                profile.active_days,
                profile.first_seen,
                profile.last_seen,
            )
            .unwrap();
        }
    }
    writeln!(out).unwrap();
}

fn write_subnets(out: &mut String, report: &ThreatReport) {
    writeln!(out, "## Network groups").unwrap();
    writeln!(out).unwrap();
    if report.subnets.is_empty() {
        writeln!(
            out,
            "No prefix reached the configured minimum number of sources."
        )
        .unwrap();
    } else {
        writeln!(out, "| Prefix | Blocks | Sources | Ports | First | Last |").unwrap();
        writeln!(out, "| --- | ---: | ---: | ---: | --- | --- |").unwrap();
        for subnet in &report.subnets {
            writeln!(
                out,
                "| `{}` | {} | {} | {} | {} | {} |",
                subnet.prefix,
                subnet.total_blocks,
                subnet.distinct_sources,
                subnet.distinct_ports,
                subnet.first_seen,
                subnet.last_seen,
            )
            .unwrap();
        }
    }
    writeln!(out).unwrap();
}

